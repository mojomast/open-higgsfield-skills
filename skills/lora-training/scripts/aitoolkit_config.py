#!/usr/bin/env python3
"""Write an ai-toolkit-style training YAML for an APPROVED dataset and print the command (never runs it).
Stdlib only. Original, this collection (MIT). Presets are starting points: UNVERIFIED field names/values -
compare with ai-toolkit's config/examples for the installed version.

  aitoolkit_config.py <folder> --model flux2_klein_4b --trigger tok --out train.yaml
"""
import argparse, json, os, sys
sys.path.insert(0, os.path.dirname(__file__))
from dataset_check import scan, set_hash

PRESETS = {
    "flux2_klein_4b": dict(arch="flux2_klein", name_or_path="black-forest-labs/FLUX.2-klein-4B", steps=2000, rank=16, lr=1e-4, res=[768, 1024]),
    "qwen_image": dict(arch="qwen_image", name_or_path="Qwen/Qwen-Image", steps=2500, rank=16, lr=1e-4, res=[768, 1024]),
    "wan22_14b": dict(arch="wan22_14b", name_or_path="Wan-AI/Wan2.2-T2V-A14B-Diffusers", steps=2000, rank=32, lr=1e-4, res=[512], frames=33),
    "ltx2": dict(arch="ltx2", name_or_path="Lightricks/LTX-2", steps=2000, rank=32, lr=1e-4, res=[512], frames=49),
}


def y(v, ind=0):
    sp = "  " * ind
    if isinstance(v, dict):
        return "\n".join(f"{sp}{k}:" + ("\n" + y(x, ind + 1) if isinstance(x, (dict, list)) and x else f" {json.dumps(x)}") for k, x in v.items())
    if isinstance(v, list):
        return "\n".join(f"{sp}-" + ("\n" + y(x, ind + 1) if isinstance(x, (dict, list)) else f" {json.dumps(x)}") for x in v)
    return sp + json.dumps(v)


def main(argv=None):
    a = argparse.ArgumentParser(); a.add_argument("folder"); a.add_argument("--model", choices=PRESETS, required=True)
    a.add_argument("--trigger", required=True); a.add_argument("--name"); a.add_argument("--out", default="train.yaml")
    a.add_argument("--steps", type=int); a.add_argument("--rank", type=int); a.add_argument("--lr", type=float)
    a = a.parse_args(argv)
    ap = os.path.join(a.folder, "APPROVED.json")
    if not os.path.exists(ap): sys.exit("REFUSED: no APPROVED.json - the user must approve the dataset first (dataset_check.py --approve)")
    if json.load(open(ap))["sha256"] != set_hash(scan(a.folder)): sys.exit("REFUSED: dataset changed after approval - re-check and re-approve")
    p = PRESETS[a.model]; name = a.name or f"{a.trigger}_{a.model}"
    ds = {"folder_path": os.path.abspath(a.folder), "caption_ext": "txt", "resolution": p["res"]}
    if "frames" in p: ds["num_frames"] = p["frames"]
    cfg = {"job": "extension", "config": {"name": name, "process": [{
        "type": "sd_trainer", "training_folder": "output", "trigger_word": a.trigger, "device": "cuda:0",
        "network": {"type": "lora", "linear": a.rank or p["rank"], "linear_alpha": a.rank or p["rank"]},
        "save": {"dtype": "float16", "save_every": 250, "max_step_saves_to_keep": 4},
        "datasets": [ds],
        "train": {"batch_size": 1, "steps": a.steps or p["steps"], "lr": a.lr or p["lr"], "optimizer": "adamw8bit", "gradient_checkpointing": True, "dtype": "bf16"},
        "model": {"name_or_path": p["name_or_path"], "arch": p["arch"], "quantize": True},
        "sample": {"sample_every": 250, "seed": 42, "prompts": [f"{a.trigger}, studio portrait, soft light", f"{a.trigger} in a rainy street at night", "a city street at night (no trigger: overfit check)"]}}]},
        "meta": {"note": "generated by lora-training/aitoolkit_config.py; preset values UNVERIFIED"}}
    open(a.out, "w").write(y(cfg) + "\n")
    print(f"wrote {a.out}\nCOMMAND (user runs it inside their ai-toolkit checkout; occupies the GPU; on Google Colab it spends compute units):\n  python run.py {os.path.abspath(a.out)}")


if __name__ == "__main__":
    main()
